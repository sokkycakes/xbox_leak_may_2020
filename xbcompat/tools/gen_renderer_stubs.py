#!/usr/bin/env python3
"""Generate the renderer client's D3D export stubs from d3d8.c's
authoritative HLE export table.  The native adapters decode arguments and
return the exact stack cleanup.

usage: gen_renderer_stubs.py d3d8.c
           x86 ABI stubs for the i386/Box86 client (entry.S)
       gen_renderer_stubs.py --translated d3d8.c d3d8.xa.inc
           adapters for a translated build (xlat), forwarding each export's
           guest frame; d3d8.xa.inc (gen_adapters.py's output for d3d8.c)
           gives each export's calling convention
"""
import re
import sys
from pathlib import Path
translated = sys.argv[1] == "--translated"
if translated:
    del sys.argv[1]
text = Path(sys.argv[1]).read_text()
marker = "const struct hle_func d3d8_funcs[] ="
if text.count(marker) != 1:
    raise SystemExit("cannot locate unique D3D export table")
table = re.sub(r"/\*.*?\*/", "", text.split(marker)[1], flags=re.S)
names = re.findall(r'F\(\s*("(?:[^"\\]|\\.)*")\s*,\s*\w+\s*\)', table)
if not names or len(names) != len(re.findall(r"\bF\s*\(", table)):
    raise SystemExit("unrecognized D3D export table entry")
if translated:
    impls = re.findall(r'F\(\s*"(?:[^"\\]|\\.)*"\s*,\s*(\w+)\s*\)', table)
    convs = dict(re.findall(r'\{ \(void \*\)(\w+), xa_\w+, (CONV_\w+),', Path(sys.argv[2]).read_text()))
    missing = [f for f in impls if f not in convs]
    if missing:
        raise SystemExit("no calling convention for " + ", ".join(missing))
    print('/* Generated by tools/gen_renderer_stubs.py --translated. */')
    print('#include "xbcompat.h"')
    print('#include "cpu.h"')
    print('#include "hle/hle.h"')
    print('uint64_t xbr_forward(uint32_t index, int conv, struct xa_frame *f);')
    print('void xbr_stub_called(uint32_t index) __attribute__((noreturn));')
    # One stub per implementation (names sharing one share its stub, as
    # hle.c expects), forwarding the first export index that names it.
    first = {}
    for i, impl in enumerate(impls):
        first.setdefault(impl, i)
    for impl, i in first.items():
        # Distinct bodies, so no two stubs share an address.
        print(f'static void xbr_stub_{i}(void) {{ xbr_stub_called({i}); }}')
        print(f'static uint64_t xbr_adapt_{i}(struct xa_frame *f) {{ return xbr_forward({i}, {convs[impl]}, f); }}')
    print('static const struct xa_entry xbr_entries[] = {')
    for impl, i in first.items():
        print(f'    {{ (void *)xbr_stub_{i}, xbr_adapt_{i}, {convs[impl]}, {names[i]} }},')
    print('};')
    print('__attribute__((constructor)) static void xbr_register(void)\n{')
    print('    xa_register(xbr_entries, sizeof(xbr_entries) / sizeof(*xbr_entries));\n}')
    print('const struct hle_func d3d8_funcs[] = {')
    for name, impl in zip(names, impls):
        print(f'    {{ {name}, (void *)xbr_stub_{first[impl]} }},')
    print('    {0, 0}\n};')
    sys.exit(0)
print('/* Generated by tools/gen_renderer_stubs.py. */')
print('#include "xbcompat.h"')
print('#include "hle/hle.h"')
for i in range(len(names)):
    print(f'extern void xbr_stub_{i}(void);')
    print(f'__asm__(".text\\n.hidden xbr_stub_{i}\\n.type xbr_stub_{i},@function\\n'
          f'xbr_stub_{i}:\\npushl {chr(36)}{i}\\njmp xbr_entry\\n");')
print('const struct hle_func d3d8_funcs[] = {')
for i, name in enumerate(names):
    print(f'    {{ {name}, xbr_stub_{i} }},')
print('    {0, 0}\n};')
