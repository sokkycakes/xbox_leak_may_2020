#!/usr/bin/env python3
"""Generate xui/xui_classes.cpp from xui/classes.json (the XUI class property
tables frolick-xui extracted from the GFWL XUI runtime, with the Xbox 360
dashboard's slot names applied the way frolick-xui's patch360 does)."""
import json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "xui", "classes.json")
dst = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "xui", "xui_classes.cpp")
chains = json.load(open(src))

# patch360: the 360 XuiControl keeps Text in slot 8 and ImagePath in slot 10.
rename = {8: "Text", 9: "_Slot9", 10: "ImagePath", 12: "_Slot12"}
seen = set()
for chain in chains.values():
    for level in chain:
        if len(level) != 13 or level[0]["n"] != "ClassOverride" or level[7]["n"] != "NavDown":
            continue
        for i, n in rename.items():
            if id(level[i]) not in seen:
                seen.add(id(level[i]))
                level[i]["n"] = n
                level[i]["t"] = 5

known_base = {"XuiBackButton": "XuiButton", "XuiNavButton": "XuiButton", "XuiCheckbox": "XuiButton",
              "XuiRadioButton": "XuiCheckbox", "XuiListItem": "XuiButton", "XuiButton": "XuiControl",
              "XuiLabel": "XuiControl"}

def level_eq(a, b):
    return len(a) == len(b) and all(x["n"] == y["n"] and x["t"] == y["t"] for x, y in zip(a, b))

def base_of(name):
    if name in known_base:
        return known_base[name]
    c = chains[name]
    if len(c) < 2:
        return ""
    for k, b in chains.items():
        if len(b) == len(c) - 1 and k != name and all(level_eq(x, y) for x, y in zip(b, c)):
            return k
    return ""

out = []
out.append("// Generated by tools/gen_classes.py from classes.json; do not edit.")
out.append('#include "xui.h"')
out.append("namespace xui {")
tables = {}   # id(level) -> table name
count = [0]

def emit_level(level, name):
    for p in level:
        if p["t"] == 9:
            emit_level(p.get("s", []), name + "_" + p["n"])
    out.append("static const PropDef %s[] = {" % name)
    for p in level:
        sub = (name + "_" + p["n"]) if p["t"] == 9 else "0"
        out.append('    { "%s", %d, %d, %s },' % (p["n"], p["t"], p["f"], sub))
    out.append("    { 0, 0, 0, 0 } };")

# Levels are shared between classes (base levels); identify by content.
level_names = {}
def key(level):
    return json.dumps(level, sort_keys=True)
for cname, chain in chains.items():
    for i, level in enumerate(chain):
        k = key(level)
        if k not in level_names:
            n = "L%d_%s" % (count[0], cname)
            count[0] += 1
            level_names[k] = n
            emit_level(level, n)
for cname, chain in chains.items():
    out.append("static const PropDef* const C_%s[] = { %s };" % (cname, ", ".join(level_names[key(l)] for l in chain)))
out.append("static const ClassDef c_classes[] = {")
for cname, chain in chains.items():
    out.append('    { "%s", "%s", C_%s, %d },' % (cname, base_of(cname), cname, len(chain)))
out.append("    { 0, 0, 0, 0 } };")
out.append("""
const ClassDef* FindClass(const char* name)
{
    for (const ClassDef* c = c_classes; c->name; c++)
        if (strcmp(c->name, name) == 0)
            return c;
    return 0;
}

bool IsA(const char* cls, const char* base)
{
    for (const ClassDef* c = FindClass(cls); c; c = FindClass(c->base)) {
        if (strcmp(c->name, base) == 0)
            return true;
        if (!c->base[0])
            break;
    }
    return false;
}

} // namespace xui""")
open(dst, "w").write("\n".join(out) + "\n")
print("wrote", dst, len(chains), "classes")
