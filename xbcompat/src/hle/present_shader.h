/* Present's fragment shader; present_program sets FILTER_X, FILTER_Y and FILTER_GAMMA per variant. */
static const char present_fs[] =
    "#ifndef FILTER_X\n"
    "#define FILTER_X 1\n"
    "#endif\n"
    "#ifndef FILTER_Y\n"
    "#define FILTER_Y 1\n"
    "#endif\n"
    "#ifndef FILTER_GAMMA\n"
    "#define FILTER_GAMMA 2\n"
    "#endif\n"
    "uniform sampler2D tex, lut;\n"
    "uniform vec2 texel, weight;\n"
    "uniform float gamma;\n"
    "varying vec2 uv;\n"
    "void main() {\n"
    "    vec3 kx = vec3(weight.x, 1.0 - 2.0 * weight.x, weight.x);\n"
    "    vec3 ky = vec3(weight.y, 1.0 - 2.0 * weight.y, weight.y);\n"
    "    vec3 c = vec3(0.0);\n"
    "#if FILTER_Y\n"
    "    for (int y = 0; y < 3; y++) {\n"
    "#else\n"
    "    { int y = 1;\n"
    "#endif\n"
    "#if FILTER_X\n"
    "        for (int x = 0; x < 3; x++) {\n"
    "#else\n"
    "    { int x = 1;\n"
    "#endif\n"
    "            c += kx[x] * ky[y] * texture2D(tex, uv + vec2(float(x - 1), float(y - 1)) * texel).rgb;\n"
    "        }\n"
    "    }\n"
    "#if FILTER_GAMMA\n"
    "    if (FILTER_GAMMA == 1 || gamma > 0.5) {\n"
    "        vec3 i = clamp(c, 0.0, 1.0) * (255.0 / 256.0) + 0.5 / 256.0;\n"
    "        c = vec3(texture2D(lut, vec2(i.r, 0.5)).r, texture2D(lut, vec2(i.g, 0.5)).g,\n"
    "                 texture2D(lut, vec2(i.b, 0.5)).b);\n"
    "    }\n"
    "#endif\n"
    "    gl_FragColor = vec4(c, 1.0);\n"
    "}\n";
