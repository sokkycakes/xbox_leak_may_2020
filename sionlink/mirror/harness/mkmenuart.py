#!/usr/bin/env python3
# The game menu's font and button pictures, baked into menuart.h (mirrorrun draws them
# with no font library). The font and the buttons are Frolick's (on the Frolick branch,
# xbcompat/tools/frolickdash/art): fonts/FiraSans-Regular.ttf and blades/[AB]-Button.png.
#   python3 mkmenuart.py FiraSans-Regular.ttf A-Button.png B-Button.png > menuart.h
# Glyphs are rendered once, large (Em pixels to the em), as 4-bit coverage; menu.cpp
# scales them down to the size and pixel shape of the TV's mode.
import sys
from PIL import Image, ImageDraw, ImageFont

Em = 44
font_path, a_path, b_path = sys.argv[1:4]
font = ImageFont.truetype(font_path, Em, layout_engine=ImageFont.Layout.BASIC)
ascent, descent = font.getmetrics()

codes = list(range(32, 127)) + list(range(160, 256)) + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2039, 0x203A]

glyphs, bits = [], bytearray()
for c in codes:
    ch = chr(c)
    adv = font.getlength(ch)
    # its box from the pen on the baseline
    l, t, r, b = font.getbbox(ch, anchor="ls")
    w, h = max(0, r - l), max(0, b - t)
    if c != 32 and (w == 0 or h == 0):
        continue
    mask = Image.new("L", (max(w, 1), max(h, 1)))
    ImageDraw.Draw(mask).text((-l, -t), ch, font=font, fill=255, anchor="ls")
    x0, y0 = l, t
    ink = mask.getbbox()   # the box above still has the side bearings in it
    if ink:
        mask = mask.crop(ink)
        x0, y0 = l + ink[0], t + ink[1]
        w, h = mask.size
    at = len(bits)
    for y in range(h):
        row = [mask.getpixel((x, y)) for x in range(w)]
        for x in range(0, w, 2):
            a = (row[x] * 15 + 127) // 255
            b = (row[x + 1] * 15 + 127) // 255 if x + 1 < w else 0
            bits.append(a | b << 4)
    glyphs.append((c, x0, y0, w, h, int(round(adv * 64)), at))


def button(path):
    im = Image.open(path).convert("RGBA")
    out = []
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = im.getpixel((x, y))
            out.append(a << 24 | r << 16 | g << 8 | b)
    return im.width, im.height, out


def array(name, ctype, values, per_line):
    s = ["static const %s %s[] = {" % (ctype, name)]
    for i in range(0, len(values), per_line):
        s.append("    " + ",".join(str(v) for v in values[i:i + per_line]) + ",")
    s.append("};")
    return "\n".join(s)


print("// Generated by mkmenuart.py: don't edit. The glyphs are rendered from Fira Sans Regular")
print("// (Digitized data copyright 2012-2016, The Mozilla Foundation and Telefonica S.A.;")
print("// SIL Open Font License 1.1, http://scripts.sil.org/OFL); the A and B buttons are the")
print("// Blades dashboard's, as Frolick uses them.")
print("#ifndef MIRROR_MENUART_H")
print("#define MIRROR_MENUART_H")
print("#include <cstdint>")
print("namespace menuart {")
print("static const int Em = %d, Ascent = %d, Descent = %d;" % (Em, ascent, descent))
print("// code point, bitmap left and top from the pen and the baseline, size, advance (1/64 px),")
print("// where its rows start in Bits (4-bit coverage, two pixels a byte, low nibble first)")
print("struct Glyph { uint16_t code; int8_t x, y; uint8_t w, h; uint16_t adv64; uint32_t at; };")
print("static const Glyph Glyphs[] = {")
for g in glyphs:
    print("    {%d, %d, %d, %d, %d, %d, %d}," % g)
print("};")
print(array("Bits", "uint8_t", list(bits), 32))
for name, path in (("ButtonA", a_path), ("ButtonB", b_path)):
    w, h, px = button(path)
    print("static const int %sW = %d, %sH = %d;   // ARGB" % (name, w, name, h))
    print(array(name, "uint32_t", px, 12))
print("}")
print("#endif")
